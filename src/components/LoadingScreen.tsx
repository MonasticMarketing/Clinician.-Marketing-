import Wordmark from "@/components/Wordmark";

/**
 * Brain loading screen, shown for ~3.5s on a full page load.
 *
 * Deliberately pure CSS and server-rendered: no JavaScript, no hydration,
 * no client component. The animation runs and ends on its own, so the
 * overlay clears even if scripts fail or are blocked — a JS-driven splash
 * that breaks leaves a permanently blank site.
 *
 * It is also pointer-events:none throughout, so it can never trap a click
 * or a scroll, and aria-hidden so screen readers go straight to the page
 * content underneath rather than waiting it out.
 *
 * The brain is a static SVG regenerated by scripts/bake-brain-points.mjs
 * from the same point cloud the hero uses, so swapping the model keeps
 * the two in sync.
 */
export default function LoadingScreen() {
  return (
    <div className="splash" aria-hidden="true">
      <div className="splash-inner">
        {/* eslint-disable-next-line @next/next/no-img-element */}
        <img
          src="/brand/brain-splash.svg"
          alt=""
          width={300}
          height={300}
          className="splash-brain"
          fetchPriority="high"
        />
        <Wordmark className="splash-mark" />
        <span className="splash-bar" />
      </div>
    </div>
  );
}
